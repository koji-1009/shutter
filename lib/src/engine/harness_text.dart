/// google_fonts resolves a font from assets, then a path_provider cache,
/// then HTTP. Cached files are served as assets so it resolves them on
/// microtasks before the first frame. path_provider is answered with null
/// so that a font missing from the cache fails inside the capture (flutter
/// test's HTTP mock answers 400) instead of after it; the failure names
/// the font's URL, which the CLI downloads before shooting again.
void _prepareGoogleFonts(List<ShutterFont> fonts) {
  final messenger =
      TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
  messenger.setMockMethodCallHandler(
    const MethodChannel('plugins.flutter.io/path_provider'),
    (call) async => null,
  );
  final assetDir = Platform.environment['UNIT_TEST_ASSETS'];
  final appName = Platform.environment['APP_NAME'];
  if (fonts.isEmpty || assetDir == null || appName == null) return;
  final served = {
    for (final font in fonts) 'shutter_fonts/${font.asset}': font.path,
  };
  final prefix = 'packages/$appName/';
  // flutter_test's own `flutter/assets` handler, plus the cached fonts.
  messenger.setMockMessageHandler('flutter/assets', (message) {
    var key = utf8.decode(message!.buffer.asUint8List());
    if (served[key] case final path?) {
      return SynchronousFuture<ByteData>(
        ByteData.sublistView(File(path).readAsBytesSync()),
      );
    }
    var asset = File('$assetDir/$key');
    if (!asset.existsSync()) {
      if (!key.startsWith(prefix)) return null;
      key = key.replaceFirst(prefix, '');
      asset = File('$assetDir/$key');
      if (!asset.existsSync()) return null;
    }
    final bytes = ByteData.sublistView(asset.readAsBytesSync());
    if (key != 'AssetManifest.bin') return SynchronousFuture<ByteData>(bytes);
    const codec = StandardMessageCodec();
    final manifest = codec.decodeMessage(bytes);
    return SynchronousFuture<ByteData>(
      codec.encodeMessage({
        if (manifest is Map<Object?, Object?>) ...manifest,
        for (final key in served.keys)
          key: [
            {'asset': key},
          ],
      })!,
    );
  });
}

Future<void> _loadFonts(
  String materialFontsDir,
  List<ShutterFont> fonts,
) async {
  Future<ByteData> readFile(File file) async =>
      ByteData.sublistView(await file.readAsBytes());
  final manifest = jsonDecode(await rootBundle.loadString('FontManifest.json'))
      as List<Object?>;
  final families = <String, List<Future<ByteData>>>{};
  for (final family in manifest.cast<Map<String, Object?>>()) {
    final fonts = family['fonts']! as List<Object?>;
    families[family['family']! as String] = [
      for (final font in fonts.cast<Map<String, Object?>>())
        rootBundle.load(font['asset']! as String),
    ];
  }
  final dir = Directory(materialFontsDir);
  if (dir.existsSync()) {
    final files = dir.listSync().whereType<File>();
    final roboto = [
      for (final file in files)
        if (file.uri.pathSegments.last.startsWith('Roboto-') &&
            file.path.endsWith('.ttf'))
          file,
    ];
    families['Roboto'] = [for (final file in roboto) readFile(file)];
    // Cupertino text names the platform's system font through these
    // families, and the test engine resolves no system font. As a macOS
    // app does, they get SF Pro from the host, which is what iOS draws;
    // elsewhere Roboto, the Android system font.
    final sf = [
      for (final name in const ['SFNS.ttf', 'SFNSItalic.ttf'])
        if (Platform.isMacOS &&
            File('/System/Library/Fonts/$name').existsSync())
          File('/System/Library/Fonts/$name'),
    ];
    final system = sf.isEmpty ? roboto : sf;
    for (final family in const [
      'CupertinoSystemText',
      'CupertinoSystemDisplay',
    ]) {
      families.putIfAbsent(
        family,
        () => [for (final file in system) readFile(file)],
      );
    }
    families.putIfAbsent('MaterialIcons', () => [
      for (final file in files)
        if (file.uri.pathSegments.last.startsWith('MaterialIcons'))
          readFile(file),
    ]);
  }
  // Registered up front: a google_fonts style created during a frame
  // registers its font after that frame's layout, too late for capture.
  for (final font in fonts) {
    families[font.family] = [readFile(File(font.path))];
  }
  for (final MapEntry(key: family, value: files)
      in _systemFallbackFonts().entries) {
    families[family] = [for (final file in files) readFile(file)];
    _fallbackFamilies.add(family);
  }
  await Future.wait([
    for (final MapEntry(key: family, value: fonts) in families.entries)
      fonts.fold(FontLoader(family), (loader, font) => loader..addFont(font))
          .load(),
  ]);
}
