/// google_fonts' failure messages: a fetched file (by hash), or, with
/// `GoogleFonts.config.allowRuntimeFetching = false`, an asset it looked
/// for (by `<Family>-<Variant>` file name prefix).
final _missingFont = RegExp(r'fonts\.gstatic\.com/s/a/([0-9a-f]{64})\.ttf');
final _missingAsset = RegExp(
  r'font (\S+) was not found in the application assets',
);

/// Device pixel ratio every shot is rendered at.
const double _pixelRatio = 2;

/// Logical viewport used when a preview does not fix a dimension.
const Size _fallbackViewport = Size(800, 600);

const Duration _precacheTimeout = Duration(seconds: 5);

void run({
  required ShutterConfig config,
  required List<ShutterEntry> entries,
  required Widget Function(Widget) defaultShell,
  required Widget Function(BuildContext, Widget, List<String>) themeFallback,
  Widget Function(Widget)? shell,
  List<ShutterFont> fonts = const [],
}) {
  _ShutterBinding();
  _defaultShell = defaultShell;
  _themeFallback = themeFallback;
  _location = RegExp(
    '(?:${RegExp.escape(Uri.directory(config.projectRoot).toString())}lib/'
    '|package:${RegExp.escape(config.packageName)}/)'
    r'([^\s:)]+\.dart):(\d+)(?::(\d+))?',
  );
  Directory('${config.runDir}/.results').createSync(recursive: true);
  if (config.googleFonts) _prepareGoogleFonts(fonts);
  if (config.networkImages.isNotEmpty) {
    HttpOverrides.global = _ServedImages(HttpOverrides.current, {
      for (final MapEntry(:key, :value) in config.networkImages.entries)
        Uri.parse(key): File(value),
    });
  }
  setUpAll(() => _loadFonts(config.materialFontsDir, fonts));
  for (final entry in entries) {
    final List<Preview> previews;
    try {
      final annotation = entry.annotation();
      previews = annotation is Preview
          ? [annotation.transform()]
          : (annotation as MultiPreview).transform();
    } catch (error, stack) {
      // The preview's name is unknown; the shot is named after the symbol.
      final id = '${entry.id}.0';
      final name = entry.symbol ?? id;
      test(id, () {
        _writeResult(config, {
          ..._entryFields(entry, id, name),
          'status': 'error',
          ..._errorFields(
            entry,
            FlutterErrorDetails(exception: error, stack: stack),
          ),
        });
      });
      continue;
    }
    for (var i = 0; i < previews.length; i++) {
      final preview = previews[i];
      final id = '${entry.id}.$i';
      final name = preview.name ?? entry.symbol ?? id;
      // Stands in for the result when the test never writes one (timeout,
      // a crash, or the test process exiting).
      _writeResult(config, {
        ..._entryFields(entry, id, name),
        'status': 'error',
        'error': 'no result: the shot timed out, or the test process '
            'stopped before it finished',
        ..._entryAt(entry),
      }, planned: true);
      testWidgets(
        id,
        (tester) => _capture(tester, config, entry, preview, id, name, shell),
        timeout: const Timeout(Duration(minutes: 2)),
      );
    }
  }
}

Map<String, Object?> _entryFields(
  ShutterEntry entry,
  String id,
  String name,
) => {
  'id': id,
  'name': name,
  'file': ?entry.file,
  'line': ?entry.line,
};

/// `at` pointing at the declaration; none for an expression.
Map<String, Object?> _entryAt(ShutterEntry entry) => {
  if (entry.file != null) 'at': '${entry.file}:${entry.line}',
};

Future<void> _capture(
  WidgetTester tester,
  ShutterConfig config,
  ShutterEntry entry,
  Preview preview,
  String id,
  String name,
  Widget Function(Widget)? shell,
) async {
  addTearDown(tester.view.reset);
  addTearDown(tester.platformDispatcher.clearAllTestValues);
  // Described while the tree is still mounted: the "relevant
  // error-causing widget" location is looked up through live elements.
  Map<String, Object?>? firstError;
  // Every google_fonts file that failed to load, not just the first
  // error's: the CLI downloads them all before shooting again.
  final missingFonts = <String>{};
  bool noteMissingFonts(String text) {
    final before = missingFonts.length;
    missingFonts
      ..addAll(_missingFont.allMatches(text).map((match) => match.group(1)!))
      ..addAll(_missingAsset.allMatches(text).map((match) => match.group(1)!));
    return missingFonts.length > before;
  }

  // flutter_test paints an elevation as a solid outline in place of its
  // shadow; a device paints the shadow. The binding checks the flag is
  // restored when the test ends.
  final previousShadows = debugDisableShadows;
  debugDisableShadows = false;
  final previous = FlutterError.onError;
  FlutterError.onError = (details) {
    firstError ??= _errorFields(entry, details);
    noteMissingFonts(details.exceptionAsString());
    previous?.call(details);
  };
  // google_fonts 8.2 and later report a font that fails to load only
  // through debugPrint; the text is still drawn, in another font. Its
  // public GoogleFonts.pendingFonts() cannot tell: under flutter_test the
  // load fails within the first pumpWidget and a failed load leaves the
  // pending set when it completes.
  final previousPrint = debugPrint;
  debugPrint = (message, {wrapWidth}) {
    if (message != null && noteMissingFonts(message)) {
      firstError ??= {
        'error': message.split('\n').first.replaceFirst('Error: ', ''),
        ..._entryAt(entry),
      };
    }
    previousPrint(message, wrapWidth: wrapWidth);
  };
  final result = <String, Object?>{
    ..._entryFields(entry, id, name),
    'brightness': ?preview.brightness?.name,
    'text_scale_factor': ?preview.textScaleFactor,
  };
  LocalizationsResolver? resolver;
  // What undoes a held action: a pressed or hovering pointer, the focus
  // highlight strategy.
  final releases = <Future<void> Function()>[];
  try {
    final size = preview.size;
    final width = size != null && size.width.isFinite ? size.width : null;
    final height = size != null && size.height.isFinite ? size.height : null;
    final viewport = switch (config.viewport) {
      (final width, final height)? => Size(width, height),
      null => Size(
        width ?? _fallbackViewport.width,
        height ?? _fallbackViewport.height,
      ),
    };
    tester.view.devicePixelRatio = _pixelRatio;
    tester.view.physicalSize = viewport * _pixelRatio;
    // The inset a device reports while its keyboard is up; the keyboard
    // itself is drawn only as its tint.
    final keyboard = config.keyboard;
    final tint = config.keyboardTint;
    if (keyboard != null) {
      tester.view.viewInsets = FakeViewPadding(bottom: keyboard * _pixelRatio);
    }
    if (preview.brightness != null) {
      tester.platformDispatcher.platformBrightnessTestValue =
          preview.brightness!;
    }
    if (preview.textScaleFactor != null) {
      tester.platformDispatcher.textScaleFactorTestValue =
          preview.textScaleFactor!;
    }

    Widget child = _subject(entry);
    final wrapper = preview.wrapper;
    if (wrapper != null) child = wrapper(child);
    final theme = preview.theme;
    if (theme != null) {
      final inner = _withFallbackFonts(child);
      child = Builder(builder: (context) => theme().apply(context, inner));
    }
    final key = GlobalKey();
    child = SizedBox(width: width, height: height, child: child);
    // The keyboard's area, painted over what the app draws there: inside
    // the captured region here, over the whole view with --capture screen
    // (below), above menus and dialogs.
    if (keyboard != null && tint != null && !config.screen) {
      child = _KeyboardTint(
        color: Color(tint),
        top: viewport.height - keyboard,
        bottom: viewport.height,
        child: child,
      );
    }
    child = RepaintBoundary(key: key, child: child);
    // Without a finite height the preview gets unbounded height, as in a
    // scrolling list, and is shot at its own height; the width stays
    // bounded by the viewport, as on a screen.
    child = _withFallbackFonts(
      OverflowBox(
        alignment: Alignment.topLeft,
        minWidth: 0,
        minHeight: 0,
        maxHeight: double.infinity,
        child: child,
      ),
    );
    final localizations = preview.localizations;
    if (localizations != null) {
      final data = localizations();
      final r = resolver = LocalizationsResolver(
        supportedLocales: data.supportedLocales,
        locale: data.locale,
        localeListResolutionCallback: data.localeListResolutionCallback,
        localeResolutionCallback: data.localeResolutionCallback,
        localizationsDelegates: data.localizationsDelegates,
      );
      child = Localizations(
        locale: r.locale,
        delegates: r.localizationsDelegates.toList(),
        child: child,
      );
    }
    child = ((wrapper == null ? shell : null) ?? _defaultShell)(child);
    if (keyboard != null && tint != null && config.screen) {
      child = Stack(
        alignment: Alignment.topLeft,
        fit: StackFit.passthrough,
        children: [
          child,
          Positioned(
            left: 0,
            right: 0,
            bottom: 0,
            height: keyboard,
            // Paint only: actions reach the app as without the tint.
            child: IgnorePointer(child: ColoredBox(color: Color(tint))),
          ),
        ],
      );
    }

    await tester.pumpWidget(child);
    await _precacheImages(tester);
    await tester.pump(Duration(milliseconds: config.settleMs));

    RenderRepaintBoundary? painted() =>
        switch (key.currentContext?.findRenderObject()) {
          final RenderRepaintBoundary region when !region.debugNeedsPaint =>
            region,
          _ => null,
        };
    // A preview the shell never paints has nothing to act on.
    final shown = painted() != null;
    if (shown) await _act(tester, config, releases);
    // The screen is the root layer: the shell's surface and what is drawn
    // above the preview (menus, dialogs, tooltips, a pushed route).
    final screen = config.screen && shown
        ? tester.binding.renderViews.first
        : null;
    final boundary = painted();
    if (shown && screen == null && boundary == null) {
      firstError ??= {
        'error': 'the preview is no longer painted after the actions (a '
            'page covers it); shoot that page through its own preview, or '
            'use --capture screen',
        ..._entryAt(entry),
      };
    }
    if (screen != null || boundary != null) {
      final size = screen?.size ?? boundary!.size;
      // The root layer already scales to the device pixel ratio, so it is
      // drawn at 1 over its bounds in physical pixels.
      final image = config.semantics
          ? _semanticsImage(
              tester,
              screen == null ? boundary!.localToGlobal(Offset.zero) : .zero,
              size,
            )
          : screen == null
          ? boundary!.toImageSync(pixelRatio: _pixelRatio)
          : (screen.debugLayer! as OffsetLayer).toImageSync(
              screen.paintBounds,
            );
      final bytes = await tester.runAsync(
        () => image.toByteData(format: ui.ImageByteFormat.png),
      );
      image.dispose();
      if (bytes != null) {
        final png = '$id.png';
        File('${config.runDir}/$png').writeAsBytesSync(
          bytes.buffer.asUint8List(bytes.offsetInBytes, bytes.lengthInBytes),
        );
        result['png'] = png;
        result['size'] = [_round(size.width), _round(size.height)];
      }
    }
  } catch (error, stack) {
    firstError ??= _errorFields(
      entry,
      FlutterErrorDetails(exception: error, stack: stack),
    );
  } finally {
    FlutterError.onError = previous;
    debugPrint = previousPrint;
    debugDisableShadows = previousShadows;
  }
  // Released while the tree they point into is still mounted.
  for (final release in releases.reversed) {
    try {
      await release();
    } catch (_) {}
  }
  try {
    await tester.pumpWidget(const SizedBox.shrink());
  } catch (_) {}
  resolver?.dispose();
  while (tester.takeException() != null) {}
  if (missingFonts.isNotEmpty) result['missing_fonts'] = [...missingFonts];
  if (firstError == null && result['png'] == null) {
    firstError = {
      'error': 'nothing was painted: the preview is not in the painted '
          'tree (does the shell or wrapper build its child?)',
      ..._entryAt(entry),
    };
  }
  if (firstError case final error?) {
    result['status'] = 'error';
    result.addAll(error);
  } else {
    result['status'] = 'ok';
  }
  _writeResult(config, result);
}

/// Paints [color] over the part of its child that lies between [top] and
/// [bottom], logical offsets from the top of the view.
class _KeyboardTint extends SingleChildRenderObjectWidget {
  const _KeyboardTint({
    required this.color,
    required this.top,
    required this.bottom,
    super.child,
  });

  final Color color;
  final double top;
  final double bottom;

  @override
  RenderObject createRenderObject(BuildContext context) =>
      _RenderKeyboardTint(color, top, bottom);
}

class _RenderKeyboardTint(
  final Color color,
  final double top,
  final double bottom,
) extends RenderProxyBox {
  @override
  void paint(PaintingContext context, Offset offset) {
    super.paint(context, offset);
    final y = localToGlobal(Offset.zero).dy;
    final from = (top - y).clamp(0.0, size.height);
    final to = (bottom - y).clamp(0.0, size.height);
    if (to <= from) return;
    context.canvas.drawRect(
      Rect.fromLTRB(
        offset.dx,
        offset.dy + from,
        offset.dx + size.width,
        offset.dy + to,
      ),
      Paint()..color = color,
    );
  }
}

/// The view's semantics tree over [size] at [origin], logical in the view,
/// drawn as Flutter's `SemanticsDebugger` draws it: a white box per node,
/// framed thicker the higher it is in the tree, in a color of its place
/// there, with its label and what it does. The whole tree is drawn and
/// cut to that region, so the preview's nodes are those the app has,
/// merged as it merges them. The debugger's painter is private, so this
/// is its drawing.
ui.Image _semanticsImage(WidgetTester tester, Offset origin, Size size) {
  final root = tester.binding.renderViews.first.owner!.semanticsOwner!
      .rootSemanticsNode!;
  final physical = size * _pixelRatio;
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  canvas.drawRect(
    Offset.zero & physical,
    Paint()..color = const Color(0xFFFFFFFF),
  );
  // Node rects are in physical pixels from the root node down, each in
  // its parent's space through its transform.
  final shift = origin * _pixelRatio;
  canvas.translate(-shift.dx, -shift.dy);
  _paintSemantics(canvas, root, _semanticsDepth(root), 0, 0);
  final picture = recorder.endRecording();
  // Rounded up, as a layer's image is, so it is the size of the shot.
  final image = picture.toImageSync(
    physical.width.ceil(),
    physical.height.ceil(),
  );
  picture.dispose();
  return image;
}

int _semanticsDepth(SemanticsNode node) {
  if (!node.hasChildren || node.mergeAllDescendantsIntoThisNode) return 1;
  var depth = 0;
  node.visitChildren((child) {
    depth = math.max(depth, _semanticsDepth(child));
    return true;
  });
  return depth + 1;
}

void _paintSemantics(
  Canvas canvas,
  SemanticsNode node,
  int rank,
  int indexInParent,
  int level,
) {
  if (node.traversalChildIdentifier != null) return;
  canvas.save();
  if (node.transform case final transform?) canvas.transform(transform.storage);
  final rect = node.rect;
  if (!rect.isEmpty) {
    final color = HSLColor.fromAHSL(
      1,
      // The debugger's seed, with its arguments as it passes them.
      360 * math.Random(indexInParent * 10000 + level).nextDouble(),
      1,
      0.7,
    ).toColor();
    final inner = rect.deflate(rank * 1.0);
    if (inner.isEmpty) {
      canvas.drawRect(rect, Paint()..color = color);
    } else {
      canvas.drawRect(rect, Paint()..color = const Color(0xFFFFFFFF));
      canvas.drawRect(
        inner,
        Paint()
          ..strokeWidth = rank * 2.0
          ..color = color
          ..style = PaintingStyle.stroke,
      );
    }
    final message = _semanticsMessage(node);
    if (message.isNotEmpty) {
      canvas.save();
      canvas.clipRect(rect);
      final text = TextPainter(
        text: TextSpan(
          text: message,
          style: TextStyle(
            color: const Color(0xFF000000),
            // Logical pixels: below the root node, which scales to the
            // device pixel ratio, the canvas is in the view's units.
            fontSize: 10,
            height: 0.8,
            fontFamily: 'Roboto',
            fontFamilyFallback: _fallbackFamilies,
          ),
        ),
        textDirection: TextDirection.ltr,
        textAlign: TextAlign.center,
      )..layout(maxWidth: rect.width);
      text.paint(canvas, Alignment.center.inscribe(text.size, rect).topLeft);
      text.dispose();
      canvas.restore();
    }
  }
  if (!node.mergeAllDescendantsIntoThisNode) {
    var index = 0;
    node.visitChildren((child) {
      _paintSemantics(canvas, child, rank - 1, index++, level + 1);
      return true;
    });
  }
  canvas.restore();
}

/// The debugger's text of [node]: its tooltip and label, then what it is
/// and does (checked, textfield, button, disabled, long-pressable,
/// scrollable, adjustable).
String _semanticsMessage(SemanticsNode node) {
  final data = node.getSemanticsData();
  final annotations = <String>[];
  var wantsTap = false;
  if (data.flagsCollection.isChecked != ui.CheckedState.none) {
    annotations.add(
      data.flagsCollection.isChecked == ui.CheckedState.isTrue
          ? 'checked'
          : 'unchecked',
    );
    wantsTap = true;
  }
  if (data.flagsCollection.isTextField) {
    annotations.add('textfield');
    wantsTap = true;
  }
  if (data.hasAction(SemanticsAction.tap)) {
    if (!wantsTap) annotations.add('button');
  } else if (wantsTap) {
    annotations.add('disabled');
  }
  if (data.hasAction(SemanticsAction.longPress)) {
    annotations.add('long-pressable');
  }
  if (data.hasAction(SemanticsAction.scrollLeft) ||
      data.hasAction(SemanticsAction.scrollRight) ||
      data.hasAction(SemanticsAction.scrollUp) ||
      data.hasAction(SemanticsAction.scrollDown)) {
    annotations.add('scrollable');
  }
  if (data.hasAction(SemanticsAction.increase) ||
      data.hasAction(SemanticsAction.decrease)) {
    annotations.add('adjustable');
  }
  // Android does not read a tooltip twice when the label repeats it.
  final label = data.attributedLabel.string;
  final tooltipAndLabel = [
    if (data.tooltip.isNotEmpty) data.tooltip,
    if (label.isNotEmpty &&
        !(defaultTargetPlatform == TargetPlatform.android &&
            label == data.tooltip))
      label,
  ].join('\n');
  if (tooltipAndLabel.isEmpty) return annotations.join('; ').trim();
  // A node with a label or tooltip always has a text direction: the
  // framework asserts it, and tests run with asserts.
  final effective = switch (data.textDirection!) {
    TextDirection.rtl => '${Unicode.RLI}$tooltipAndLabel${Unicode.PDI}',
    TextDirection.ltr => tooltipAndLabel,
  };
  return (annotations.isEmpty
          ? effective
          : '$effective (${annotations.join('; ')})')
      .trim();
}

/// Two decimals: enough to read, stable against float noise.
double _round(double value) => (value * 100).roundToDouble() / 100;

Widget _subject(ShutterEntry entry) {
  final built = Function.apply(entry.target, const []);
  if (built is Widget) return built;
  if (built is WidgetBuilder) return Builder(builder: built);
  throw StateError(
    '${entry.symbol ?? 'the expression'} returned ${built.runtimeType}; '
    'a preview must return a Widget or a WidgetBuilder.',
  );
}

Future<void> _precacheImages(WidgetTester tester) async {
  final images = find.byType(Image, skipOffstage: false).evaluate().toList();
  if (images.isEmpty) return;
  await tester.runAsync(() async {
    await Future.wait([
      for (final element in images)
        precacheImage((element.widget as Image).image, element)
            .timeout(_precacheTimeout, onTimeout: () {}),
    ]);
  });
  await tester.pump();
}

/// Performs the run's actions on the mounted preview, each followed by
/// one `pump(settle)`. What undoes a held action goes to [releases].
Future<void> _act(
  WidgetTester tester,
  ShutterConfig config,
  List<Future<void> Function()> releases,
) async {
  // Semantics labels exist only while semantics are on; one frame builds
  // them, without advancing the clock.
  if (config.actions.any((action) => action.by == .label)) {
    final semantics = tester.ensureSemantics();
    releases.add(() async => semantics.dispose());
    await tester.pump();
  }
  for (final action in config.actions) {
    final element = _target(action);
    switch (action.kind) {
      case .tap:
        await tester.tapAt(_hitPoint(tester, action, element));
      case .enter:
        _textField(action, element);
        // Focuses the field and replaces its text, as the platform's
        // keyboard does; the test engine draws no keyboard.
        await tester.enterText(action.finder, action.text!);
      case .press:
        final gesture = await tester.startGesture(
          _hitPoint(tester, action, element),
        );
        releases.add(gesture.cancel);
      case .hover:
        // Added where it hovers, so it passes over no other widget.
        final mouse = await tester.createGesture(kind: PointerDeviceKind.mouse);
        await mouse.addPointer(location: _hitPoint(tester, action, element));
        releases.add(mouse.removePointer);
      case .focus:
        final node = _focusNode(action, element);
        // flutter_test runs as a touch device, where focus draws no
        // highlight; a keyboard would.
        final manager = FocusManager.instance;
        final previous = manager.highlightStrategy;
        manager.highlightStrategy = FocusHighlightStrategy.alwaysTraditional;
        releases.add(() async => manager.highlightStrategy = previous);
        node.requestFocus();
    }
    await _frames(tester, config.settleMs);
  }
}

/// Frame interval of a 60 Hz display.
const _frame = Duration(milliseconds: 16);

/// Advances [ms] in frames, as a device draws them. One long pump would
/// draw a single frame, in which an animation an action starts (ink, a
/// check mark, a route) is only beginning, and a timer the action set (a
/// tap's down, after `kPressTimeout`) would start its animation there.
Future<void> _frames(WidgetTester tester, int ms) async {
  final total = Duration(milliseconds: ms);
  var elapsed = Duration.zero;
  do {
    final step = total - elapsed < _frame ? total - elapsed : _frame;
    await tester.pump(step);
    elapsed += step;
  } while (elapsed < total);
}

/// The one widget [action] names.
Element _target(ShutterAction action) {
  final found = action.finder.evaluate().toList();
  return switch (found) {
    [final element] => element,
    [] => throw _ActionError('${action.label}: no widget matches'),
    _ => throw _ActionError(
      '${action.label}: ${found.length} widgets match; name one',
    ),
  };
}

/// The centre of [element], where a pointer reaches it; as `tap` in
/// flutter_test, but a miss is an error rather than a warning.
Offset _hitPoint(WidgetTester tester, ShutterAction action, Element element) {
  final box = element.renderObject;
  if (box is! RenderBox || !box.hasSize) {
    throw _ActionError('${action.label}: the widget is not laid out');
  }
  final point = box.localToGlobal(box.size.center(Offset.zero));
  final hit = tester.hitTestOnBinding(point);
  if (!hit.path.any((entry) => entry.target == box)) {
    throw _ActionError(
      '${action.label}: a pointer at its centre does not reach it '
      '(covered, outside the viewport, or ignoring pointers)',
    );
  }
  return point;
}

/// Checks that [element] is, or holds, exactly one `EditableText`, which
/// `enterText` types into.
void _textField(ShutterAction action, Element element) {
  var fields = element.widget is EditableText ? 1 : 0;
  void visit(Element child) {
    if (child.widget is EditableText) fields++;
    child.visitChildren(visit);
  }

  element.visitChildren(visit);
  if (fields == 0) {
    throw _ActionError('${action.label}: the widget holds no text field');
  }
  if (fields > 1) {
    throw _ActionError(
      '${action.label}: the widget holds $fields text fields; name one',
    );
  }
}

/// The focus node of [element]: the first one inside it (a button's or
/// text field's own), else the one around it.
FocusNode _focusNode(ShutterAction action, Element element) {
  final around = Focus.maybeOf(element, createDependency: false);
  FocusNode? inside;
  void visit(Element child) {
    if (inside != null) return;
    final node = Focus.maybeOf(child, createDependency: false);
    if (node != null && node != around) {
      inside = node;
      return;
    }
    child.visitChildren(visit);
  }

  element.visitChildren(visit);
  final node = inside ?? around;
  if (node == null || !node.canRequestFocus) {
    throw _ActionError('${action.label}: the widget cannot take focus');
  }
  return node;
}

/// The first line of the error, and `at`: the first `lib/` location in its
/// report, else the failing `Image`'s, else the preview's own (none for an
/// expression).
Map<String, Object?> _errorFields(
  ShutterEntry entry,
  FlutterErrorDetails details,
) {
  final message = details
      .exceptionAsString()
      .split('\n')
      .map((line) => line.trim())
      .firstWhere((line) => line.isNotEmpty, orElse: () => 'unknown error');
  final at =
      _locate('${details.toString()}\n${details.stack ?? ''}') ??
      _imageLocation(details);
  return {
    'error': message,
    if (at != null) 'at': at else ..._entryAt(entry),
  };
}

/// Image load errors carry the failing `ImageProvider` but no widget
/// location. Finds the mounted `Image` showing that provider and reads
/// its creation location the way the framework does for layout errors.
String? _imageLocation(FlutterErrorDetails details) {
  final providers = [
    for (final node in details.informationCollector?.call() ??
            const <DiagnosticsNode>[])
      if (node.value case final ImageProvider<Object> provider) provider,
  ];
  if (providers.isEmpty) return null;
  Element? found;
  void visit(Element element) {
    if (found != null) return;
    final widget = element.widget;
    if (widget is Image && providers.contains(widget.image)) {
      found = element;
      return;
    }
    element.visitChildren(visit);
  }

  WidgetsBinding.instance.rootElement?.visitChildren(visit);
  final element = found;
  if (element == null) return null;
  final described = FlutterErrorDetails(
    exception: '',
    informationCollector: () => [
      DiagnosticsDebugCreator(DebugCreator(element)),
    ],
  ).toString();
  return _locate(described);
}

/// A `lib/` file of the project, as a file or `package:` URI, with its
/// line and column. Set by [run].
late final RegExp _location;

/// First `lib/...:line:column` of the project named in [text]. Generated
/// code under `.dart_tool/shutter/` never counts.
String? _locate(String text) {
  final match = _location.firstMatch(text);
  if (match == null) return null;
  final path = 'lib/${match.group(1)!}';
  final column = match.group(3);
  return column == null
      ? '$path:${match.group(2)}'
      : '$path:${match.group(2)}:$column';
}

